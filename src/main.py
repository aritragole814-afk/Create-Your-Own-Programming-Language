"""Command-line entry point, compiler phase inspector, and interactive REPL for NovaLang."""

import argparse
import sys
from pathlib import Path

# Ensure project root is in sys.path
PROJECT_ROOT = Path(__file__).resolve().parent.parent
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

from src.interpreter import Interpreter, NovaRuntimeError
from src.lexer import Lexer, NovaLexError
from src.parser import NovaSyntaxError, Parser


BANNER = r"""
=====================================================
    _   __                 __                    
   / | / /___ _   ______ _/ /   ____ _____  ____ 
  /  |/ / __ \ | / / __ `/ /   / __ `/ __ \/ __ \
 / /|  / /_/ / |/ / /_/ / /___/ /_/ / / / / /_/ /
/_/ |_/\____/|___/\__,_/_____/\__,_/_/ /_/\__, / 
                                         /____/  
   NovaLang: Modern Interpreted Programming Language
   Compiler Design Project-Based Learning (PBL)
=====================================================
"""


def compile_and_run(
    source: str,
    interpreter: Interpreter | None = None,
    show_tokens: bool = False,
    show_ast: bool = False,
) -> Interpreter:
    """Compile and evaluate source code through all compiler phases."""
    # Phase 1: Lexical Analysis
    lexer = Lexer(source)
    tokens = lexer.tokenize()

    if show_tokens:
        print("\n--- [Phase 1: Lexical Analysis (Tokens)] ---")
        for token in tokens:
            print(f"  {token}")
        print("-------------------------------------------\n")

    # Phase 2: Syntax Analysis & AST Construction
    parser = Parser(tokens)
    statements = parser.parse()

    if show_ast:
        print("\n--- [Phase 2: Abstract Syntax Tree (AST)] ---")
        for stmt in statements:
            print(stmt.to_tree_str())
        print("---------------------------------------------\n")

    # Phase 3: Interpretation & Evaluation
    if show_tokens or show_ast:
        print("--- [Phase 3: Execution Output] ---")

    active_interpreter = interpreter if interpreter is not None else Interpreter()
    active_interpreter.interpret(statements)

    if show_tokens or show_ast:
        print("-----------------------------------")

    return active_interpreter


def _is_complete_block(source: str) -> bool:
    """Check if braces and parentheses are balanced for multiline REPL input."""
    try:
        tokens = Lexer(source).tokenize()
    except NovaLexError:
        return True

    brace_depth = 0
    paren_depth = 0
    meaningful = [t for t in tokens if t.lexeme]
    if not meaningful:
        return True

    for t in meaningful:
        if t.lexeme == "{":
            brace_depth += 1
        elif t.lexeme == "}":
            brace_depth -= 1
        elif t.lexeme == "(":
            paren_depth += 1
        elif t.lexeme == ")":
            paren_depth -= 1

    return brace_depth <= 0 and paren_depth <= 0 and (
        meaningful[-1].lexeme in (";", "}")
    )


def start_repl() -> None:
    """Start the interactive NovaLang Read-Eval-Print Loop."""
    print("Welcome to NovaLang interactive prompt (REPL).")
    print("Commands: ':quit' or ':exit' to exit, ':clear' to clear scope.")
    print("Type statements ending in ';' or blocks enclosed in '{ ... }'.\n")

    interpreter = Interpreter()
    buffer: list[str] = []

    while True:
        prompt = "... " if buffer else "nova> "
        try:
            line = input(prompt)
        except EOFError:
            print("\nExiting NovaLang.")
            return
        except KeyboardInterrupt:
            print("\nUse ':quit' to exit.")
            buffer.clear()
            continue

        stripped = line.strip()
        if not buffer:
            if stripped in (":quit", ":exit"):
                print("Goodbye!")
                return
            if stripped == ":clear":
                interpreter = Interpreter()
                print("Environment cleared.")
                continue

        buffer.append(line)
        source = "\n".join(buffer)

        if not _is_complete_block(source):
            continue

        try:
            compile_and_run(source, interpreter)
        except (NovaLexError, NovaSyntaxError, NovaRuntimeError) as err:
            print(f"\033[91m{err}\033[0m", file=sys.stderr)
        except Exception as ex:
            print(f"\033[91mUnexpected error: {ex}\033[0m", file=sys.stderr)
        finally:
            buffer.clear()


def main() -> int:
    parser = argparse.ArgumentParser(
        description="NovaLang: Custom Programming Language for Compiler Design PBL."
    )
    parser.add_argument("file", nargs="?", help="Path to a .nova source file to execute.")
    parser.add_argument(
        "--tokens",
        action="store_true",
        help="Display the stream of tokens generated by the Lexical Analyzer.",
    )
    parser.add_argument(
        "--ast",
        action="store_true",
        help="Display the Abstract Syntax Tree (AST) produced by the Parser.",
    )

    args = parser.parse_args()

    if args.file is None:
        print(BANNER)
        start_repl()
        return 0

    file_path = Path(args.file)
    if not file_path.exists():
        print(f"Error: File '{args.file}' not found.", file=sys.stderr)
        return 1

    try:
        source_code = file_path.read_text(encoding="utf-8")
        compile_and_run(
            source_code,
            show_tokens=args.tokens,
            show_ast=args.ast,
        )
    except (NovaLexError, NovaSyntaxError, NovaRuntimeError) as err:
        print(f"Execution failed:\n{err}", file=sys.stderr)
        return 1
    except OSError as err:
        print(f"File system error: {err}", file=sys.stderr)
        return 1

    return 0


if __name__ == "__main__":
    sys.exit(main())
